	public static final int MIN_DOSES = 1;
	public static final int MAX_DOSES = 4;

	// Index 0 holds the 1-dose item ID, index 3 the 4-dose item ID
	private final int[] doseItemIds;

	Potion(int oneDoseItemId, int twoDoseItemId, int threeDoseItemId, int fourDoseItemId)
	{
		this.doseItemIds = new int[]{ oneDoseItemId, twoDoseItemId, threeDoseItemId, fourDoseItemId };
	}

	/**
	 * Returns the item ID of the variant with the given amount of doses, or -1 if the amount is invalid.
	 */
	public int getDoseItemId(int doses)
	{
		if (doses < MIN_DOSES || doses > MAX_DOSES)
		{
			return -1;
		}
		return doseItemIds[doses - 1];
	}

	/**
	 * Returns the amount of doses the given item ID represents for this potion, or -1 if the item is not one of
	 * its dose variants.
	 */
	public int getDoses(int itemId)
	{
		for (int i = 0; i < doseItemIds.length; i++)
		{
			if (doseItemIds[i] == itemId)
			{
				return i + 1;
			}
		}
		return -1;
	}

	private static final Map<Integer, Potion> BY_ITEM_ID = new HashMap<>();

	static
	{
		for (Potion potion : values())
		{
			for (int itemId : potion.doseItemIds)
			{
				BY_ITEM_ID.put(itemId, potion);
			}
		}
	}

	/**
	 * Returns the potion the given item ID is a dose variant of, or null if it is not a known potion item.
	 */
	public static Potion getByItemId(int itemId)
	{
		return BY_ITEM_ID.get(itemId);
	}
