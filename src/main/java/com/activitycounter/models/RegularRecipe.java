package com.activitycounter.models;

import lombok.Getter;
import net.runelite.api.gameval.ItemID;
import static net.runelite.api.gameval.ItemID.*;

/**
 * A standard herblore recipe: a single base item (e.g. an unfinished potion) combined with a single ingredient,
 * producing one item of a fixed form. Each action consumes exactly one base item and one ingredient.
 */
@Getter
public enum RegularRecipe implements BaseRecipe
{
	ATTACK_POTION(GUAMVIAL, EYE_OF_NEWT, _3DOSE1ATTACK),
	SUPER_ATTACK_POTION(IRITVIAL, EYE_OF_NEWT, _3DOSE2ATTACK),
	ANTIPOISON(MARRENTILLVIAL, UNICORN_HORN_DUST, _3DOSEANTIPOISON),
	SUPERANTIPOISON(IRITVIAL, UNICORN_HORN_DUST, _3DOSE2ANTIPOISON),
	STRENGTH_POTION(TARROMINVIAL, LIMPWURT_ROOT, _3DOSE1STRENGTH),
	SUPER_STRENGTH_POTION(KWUARMVIAL, LIMPWURT_ROOT, _3DOSE2STRENGTH),
	COMPOST_POTION(HARRALANDERVIAL, FOSSIL_VOLCANIC_ASH, SUPERCOMPOST_POTION_3),
	RESTORE_POTION(HARRALANDERVIAL, RED_SPIDERS_EGGS, _3DOSESTATRESTORE),
	SUPER_RESTORE(SNAPDRAGONVIAL, RED_SPIDERS_EGGS, _3DOSE2RESTORE),
	WEAPON_POISON_PLUS(UNFINISHED_WEAPON_POISON_, RED_SPIDERS_EGGS, WEAPON_POISON_),
	ENERGY_POTION(HARRALANDERVIAL, CHOCOLATE_DUST, _3DOSE1ENERGY),
	DEFENCE_POTION(RANARRVIAL, WHITE_BERRIES, _3DOSE1DEFENSE),
	SUPER_DEFENCE_POTION(CADANTINEVIAL, WHITE_BERRIES, _3DOSE2DEFENSE),
	AGILITY_POTION(TOADFLAXVIAL, TOADS_LEGS, _3DOSE1AGILITY),
	COMBAT_POTION(HARRALANDERVIAL, GROUND_DESERT_GOAT_HORN, _3DOSECOMBAT),
	PRAYER_POTION(RANARRVIAL, SNAPE_GRASS, _3DOSEPRAYERRESTORE),
	FISHING_POTION(AVANTOEVIAL, SNAPE_GRASS, _3DOSEFISHERSPOTION),
	SUPER_ENERGY(AVANTOEVIAL, MORTMYREMUSHROOM, _3DOSE2ENERGY),
	HUNTER_POTION(KWUARMVIAL, HUNTINGBEAST_SABRETEETH_DUST, _3DOSEHUNTING),
	WEAPON_POISON(KWUARMVIAL, DRAGON_SCALE_DUST, net.runelite.api.gameval.ItemID.WEAPON_POISON),
	ANTIFIRE_POTION(LANTADYMEVIAL, DRAGON_SCALE_DUST, _3DOSE1ANTIDRAGON),
	ANTIDOTE_PLUS(UNFINISHED_ANTIDOTE_, YEW_ROOTS, ANTIDOTE_4),
	RANGING_POTION(DWARFWEEDVIAL, WINE_OF_ZAMORAK, _3DOSERANGERSPOTION),
	BASTION_POTION(CADANTINE_BLOODVIAL, WINE_OF_ZAMORAK, _3DOSEBASTION),
	MAGIC_POTION(LANTADYMEVIAL, CACTUS_POTATO, _3DOSE1MAGIC),
	BATTLEMAGE_POTION(CADANTINE_BLOODVIAL, CACTUS_POTATO, _3DOSEBATTLEMAGE),
	ZAMORAK_BREW(TORSTOLVIAL, JANGERBERRIES, _3DOSEPOTIONOFZAMORAK),
	ANTIDOTE_PLUSPLUS(UNFINISHED_ANTIDOTE__, MAGIC_ROOTS, ANTIDOTE__4),
	SARADOMIN_BREW(TOADFLAXVIAL, CRUSHED_BIRD_NEST, _3DOSEPOTIONOFSARADOMIN),
	SURGE_POTION(TORSTOLVIAL, DEMONIC_TALLOW, _3DOSESURGE),
	WEAPON_POISON_PLUSPLUS(UNFINISHED_WEAPON_POISON__, POISONIVY_BERRIES, WEAPON_POISON__),
	ANCIENT_BREW(DWARFWEEDVIAL, NIHIL_DUST, _3DOSEANCIENTBREW),
	GOADING_POTION(HARRALANDERVIAL, ALDARIUM, _3DOSEGOADING),
	PRAYER_REGENERATION_POTION(HUASCAVIAL, ALDARIUM, _3DOSE1PRAYER_REGENERATION),
	HAEMOSTATIC_POULTICE(ELKHORNVIAL, SQUID_PASTE, ItemID.HAEMOSTATIC_POULTICE),
	HAEMOSTATIC_DRESSING(ItemID.HAEMOSTATIC_POULTICE, COTTON_YARN, _3DOSEHAEMOSTATICDRESSING),
	SUPER_FISHING_POTION(PILLARVIAL, HADDOCK_EYE, _3DOSE2FISHERSPOTION),
	SUPER_HUNTER_POTION(PILLARVIAL, CRAB_PASTE, _3DOSE2HUNTING),
	ARMADYL_BREW(UMBRALVIAL, RAINBOW_CRAB_PASTE, _3DOSEARMADYLBREW),
	;

	private final int baseItemId;
	private final int ingredientItemId;
	private final int producedItemId;

	RegularRecipe(int baseItemId, int ingredientItemId, int producedItemId)
	{
		this.baseItemId = baseItemId;
		this.ingredientItemId = ingredientItemId;
		this.producedItemId = producedItemId;
	}

	@Override
	public int[] getBaseItemIds()
	{
		return new int[]{ baseItemId };
	}

	@Override
	public int getProducedItemId(int baseDoses)
	{
		return producedItemId;
	}
}
